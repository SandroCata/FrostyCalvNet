#!/usr/bin/env python3
"""Organize preprocessed patches for training.

Moves target/context image patches and corresponding zone masks generated by
``generate_target_context.py`` into the directory layout expected by
``train.py``. Only SAR images and zones masks are considered; fronts masks are
ignored.
"""

from pathlib import Path
import shutil


def move_files(src: Path, dst: Path) -> None:
    """Move all PNG files from *src* directory to *dst* directory."""
    dst.mkdir(parents=True, exist_ok=True)
    if not src.exists():
        print(f"Source directory {src} not found, skipping.")
        return
    for file in src.glob("*.png"):
        shutil.move(str(file), dst / file.name)


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    caffe_dir = root / "CAFFE"
    preprocessed_dir = root / "Preprocessed_CAFFE_zones"

    # Ensure expected directory tree exists under Preprocessed_CAFFE
    for split in ("Training", "Validation", "Testing"):
        for sub in ("target_images", "context_images", "target_masks", "context_masks"):
            (preprocessed_dir / split / sub).mkdir(parents=True, exist_ok=True)

    mappings = {
        # Training
        caffe_dir / "sar_images" / "target_imgs": preprocessed_dir / "Training" / "target_images",
        caffe_dir / "sar_images" / "context_imgs": preprocessed_dir / "Training" / "context_images",
        caffe_dir / "zones" / "target_imgs": preprocessed_dir / "Training" / "target_masks",
        caffe_dir / "zones" / "context_imgs": preprocessed_dir / "Training" / "context_masks",
        # Validation
        caffe_dir / "sar_images" / "target_imgs_valid": preprocessed_dir / "Validation" / "target_images",
        caffe_dir / "sar_images" / "context_imgs_valid": preprocessed_dir / "Validation" / "context_images",
        caffe_dir / "zones" / "target_imgs_valid": preprocessed_dir / "Validation" / "target_masks",
        caffe_dir / "zones" / "context_imgs_valid": preprocessed_dir / "Validation" / "context_masks",
        # Testing
        caffe_dir / "sar_images" / "target_imgs_test": preprocessed_dir / "Testing" / "target_images",
        caffe_dir / "sar_images" / "context_imgs_test": preprocessed_dir / "Testing" / "context_images",
        caffe_dir / "zones" / "target_imgs_test": preprocessed_dir / "Testing" / "target_masks",
        caffe_dir / "zones" / "context_imgs_test": preprocessed_dir / "Testing" / "context_masks",
    }

    for src, dst in mappings.items():
        move_files(src, dst)

    print("Reorganization complete.")